"""
权限系统面向**用户**的文案（纯函数，零 IO）。

本模块只做一件事：把权限层的某个结果翻译成一段给人读的话。它不参与任何判定，
判定全在 `engine` / `rules` / `network` / `protected` 里。

与 `classifier/render.py`、`team/render.py`、`todo/render.py` 是同一形态——
每个包把「给人看的措辞」收在一处，理由是那些措辞要反复打磨，而打磨措辞
不该顺手动到判定逻辑。

⚠ **本模块刻意只依赖标准库。** 它被协调层在事件流中途调用，
拉进任何重依赖都会让「产出一句提示」变成一次可能失败的操作。
"""

from __future__ import annotations


def render_permanent_allow_fallback(rule_string: str, reason: str) -> str:
    """
    「永久放行」写盘失败、已降级为「本会话放行」时给用户的提示。

    :param rule_string: 用户批准的那条规则原文，如 `"Bash(git status)"`
    :param reason: 失败原因（`PermissionEngine.persist_local_rule` 的返回值）
    :returns: 一段多行文本；缺规则原文时仍照常产出（原因是主信息）

    副作用：无（纯函数）。

    ## 为什么这条提示必须存在

    确认面板上那个选项写的是「永久放行 —— 写入本地配置，**重启仍生效**」
    （`tui/widgets.py` 的 `ConfirmPanel.show_for`）。写盘失败时代码会改加一条
    **会话级**规则、照常放行本次——于是用户看到的是「面板消失、一切正常」，
    他有充分理由相信这条授权已经落盘，而它重启就没了。

    ⚠ 这与已知项 #18「**错误的安全承诺比没有承诺更危险**」、以及成对维护点里
    「计划审批面板那句说明 ↔ `auto` 预设的档位」是同一形态：
    **面板上一句与实际行为不符的话，比没有那句话更糟。**

    ⚠ **别把面板文案改成「可能写入本地配置」来回避本提示**：那是把一句准确的
    承诺换成一句含糊的，用户依然不知道这一次到底写没写。要么当场说实话
    （本函数），要么在他按下按钮之前就说。

    ## 四件事一件都不能少

    1. **没写进去**——推翻他刚读到的那句「重启仍生效」；
    2. **本次仍然放行了**——不说的话他会以为整个操作失败了，跑回去重试；
    3. **本会话内有效、重启失效**——他要据此决定现在要不要去修那个文件；
    4. **为什么 + 怎么办**——原因串里已经带了出问题的文件路径。
    """
    head = "警告：这条「永久放行」没有写进本地配置，已降级为**本会话放行**。"
    lines = [head]
    if rule_string:
        lines.append(f"  规则：{rule_string}")
    lines.append(f"  原因：{reason}")
    lines.append(
        "  影响：本次调用已放行，本会话内相同调用也不再询问；"
        "**但重启后这条授权就没了**（面板上那句「重启仍生效」这次没有兑现）。"
    )
    lines.append(
        "  怎么办：去看上面那个文件——它多半是坏的（本地级配置的顶层必须是"
        "`allow:` / `deny:` 这样的映射，不能写成 YAML 列表），"
        "修好后重新点一次「永久放行」即可。"
    )
    return "\n".join(lines)
