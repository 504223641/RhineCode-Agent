"""
Plan Mode 引导 system prompt 构造（spec F11）。

Plan Mode 开启时，ConversationManager 会把本模块产出的提示作为一条 role="system" 消息
前置注入到每一轮请求中（仅 Plan Mode 注入，不写入持久对话历史）。它的作用是把模型从
「拿到需求直接动手」引导为「先规划、按需澄清、用户审批后再执行」的两段式工作方式。

注意：仅靠「只暴露只读工具」也能阻止模型修改文件，但模型未必会主动产出结构化计划、
也不知道可以用 ask_user / present_plan 与用户交互——因此需要这段引导提示明确告知流程。
"""


def build_plan_prompt() -> str:
    """
    构造 Plan Mode 的引导 system prompt。

    :returns: 一段中文提示文本，告知模型在规划阶段的行为约束与可用的两个交互工具

    副作用：无（纯文本构造）。
    """
    return (
        "你现在处于「计划模式（Plan Mode）」。在用户明确批准之前，你只能调研、不能执行任何"
        "修改类操作（不要写文件、改文件或执行命令），当前也只为你开放了只读工具。\n"
        "\n"
        "请按以下流程工作：\n"
        "1. 先用只读工具（读文件、查找文件、搜索代码等）充分调研，理解现状与需求。\n"
        "2. 如果需求中存在不清楚、有歧义或需要用户拍板的细节，使用 ask_user 工具逐一向用户提问："
        "每次提一个问题并给出若干候选项；每个候选项包含 summary（一句话概述）和 detail（详细说明与取舍）；"
        "把你最推荐的候选项放在 options 列表的第一个。\n"
        "3. 调研与澄清完成后，使用 present_plan 工具提交一份清晰的计划（plan 字段）等待用户审批。\n"
        "4. 只有当用户通过 present_plan 批准后，才会为你开放全部工具，你才能开始执行计划。\n"
        "\n"
        "即使需求看起来已经很明确、无需澄清，也必须先用 present_plan 提交计划并取得批准，再执行。"
    )
