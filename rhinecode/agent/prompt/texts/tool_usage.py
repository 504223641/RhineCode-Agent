    "- **同一步里能一起发的调用就一起发。** 若这一步打算调用多个工具且它们之间"
    "没有依赖，就在同一次回复里把它们全部发出、并行执行；只有当后一个工具的参数"
    "依赖前一个的结果时，才必须等结果返回再发下一个。不要把本可并行的只读查询"
