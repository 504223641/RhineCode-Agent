"""
交付标准模块文案（对应 fixed_modules 中 priority=35 的「交付标准」模块）。

只存放 prompt 正文常量，不含逻辑。

## 这个模块解决什么问题

其余七个模块讲的都是「事情顺利时怎么做」，而模型最常见、代价最大的失败恰恰在
不顺利的那一侧。本模块补的就是这一类，四件事：

1. **防范围收窄**。`TASK_MODE` 原先只写了「避免顺手重构、扩大范围」——那只防了
   一个方向。反方向（三件事做完两件、然后写一段让人以为三件都做了的总结）
   更常见也更有害，因为用户**看不出来**。
2. **异议之后仍然交付**。模型对任务有顾虑时容易停在「我建议不要这么做」，
   把决定权拿走了。正确形态是「说清顾虑 + 照做」。
3. **如实报告**。测试红了要说红了并附输出，跳过了要说跳过。
4. **反向的对冲词约束**。这条容易被忽略：光要求「不确定就说不确定」会让模型对
   **做对的事**也加「应该可以」——满篇对冲等于没有信号，用户反而分不出
   哪几处是真的没把握。

## 为什么排在 35（任务模式 30 与 动作执行 40 之间）

语义上是递进的三段：`TASK_MODE` 讲**怎么推进**，本模块讲**推进到什么程度算数**，
`ACTION_EXECUTION` 讲**每个动作的边界**。夹在中间读起来是一条连贯的链。

⚠️ 措辞上刻意避开了 `tests/test_c5_prompt.py::test_seven_fixed_modules_in_order`
用到的那几个定位标记（「调研 → 行动」「有副作用的操作」「工具使用准则」等）。
那个用例用 `str.find` 取**首次**出现位置来判断模块顺序，本模块若碰巧包含别的
模块的标记词，会把那个模块的判定位置提前，造成难以排查的假失败。
"""

